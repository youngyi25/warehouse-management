<template>
  <div class="login-container">
    <el-card class="login-card">
      <h2 class="title">仓库管理系统</h2>
      <el-form :model="loginForm" :rules="rules" ref="loginForm" class="login-form">
        <el-form-item prop="username">
          <el-input v-model="loginForm.username" placeholder="用户名" prefix-icon="el-icon-user"></el-input>
        </el-form-item>
        <el-form-item prop="password">
          <el-input v-model="loginForm.password" placeholder="密码" prefix-icon="el-icon-lock" show-password @keyup.enter.native="handleLogin"></el-input>
        </el-form-item>
        <el-form-item>
          <el-button type="primary" :loading="loading" @click="handleLogin" class="login-btn">登 录</el-button>
        </el-form-item>
      </el-form>
    </el-card>
  </div>
</template>

<script>
export default {
  name: 'Login',
  data() {
    return {
      loginForm: {
        username: 'admin',
        password: 'admin123'
      },
      rules: {
        username: [{ required: true, message: '请输入用户名', trigger: 'blur' }],
        password: [{ required: true, message: '请输入密码', trigger: 'blur' }]
      },
      loading: false
    }
  },
  methods: {
    handleLogin() {
      this.$refs.loginForm.validate(valid => {
        if (valid) {
          this.loading = true
          this.$store.dispatch('user/login', this.loginForm)
            .then(() => {
              return this.$store.dispatch('user/getUserInfo')
            })
            .then(() => {
              const redirect = this.$route.query.redirect || '/'
              this.$router.replace(redirect).catch(err => {
                if (err.name !== 'NavigationDuplicated') {
                  throw err
                }
              })
              this.$message.success('登录成功')
            })
            .catch((error) => {
              console.error('登录错误:', error)
              this.$message.error('登录失败，请检查用户名和密码')
            })
            .finally(() => {
              this.loading = false
            })
        }
      })
    }
  }
}
</script>

